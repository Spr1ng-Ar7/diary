/* ---------- 随机工具 ---------- */
function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

/* 随机取一句治愈文案，尽量不与上一句重复 */
var lastHealingIdx = -1;
function pickHealing() {
  var i;
  do { i = Math.floor(Math.random() * HEALING_LINES.length); }
  while (i === lastHealingIdx && HEALING_LINES.length > 1);
  lastHealingIdx = i;
  return HEALING_LINES[i];
}
